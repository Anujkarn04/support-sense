
"""Evaluate early-message text escalation models with 5-fold CV."""

from pathlib import Path

import pandas as pd
from sklearn.base import clone
from sklearn.dummy import DummyClassifier
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import Pipeline

ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = ROOT / "data" / "processed"
REPORT_DIR = ROOT / "reports" / "escalation"

CHECKPOINTS = (3, 5)
RANDOM_STATE = 42


def make_model():
    return Pipeline([
        ("tfidf", TfidfVectorizer(
            lowercase=True,
            strip_accents="unicode",
            ngram_range=(1, 2),
            min_df=2,
            max_features=10000,
            sublinear_tf=True,
        )),
        ("classifier", LogisticRegression(
            class_weight="balanced",
            max_iter=2000,
            random_state=RANDOM_STATE,
        )),
    ])


def main():
    REPORT_DIR.mkdir(parents=True, exist_ok=True)

    datasets = {}
    for checkpoint in CHECKPOINTS:
        path = DATA_DIR / f"escalation_text_message_{checkpoint}_dataset.csv"
        data = pd.read_csv(path)

        if data["conversation_id"].duplicated().any():
            raise ValueError(f"Duplicate conversation IDs in {path.name}")

        data = data.dropna(subset=["customer_text", "escalation_label"])
        data = data[data["escalation_label"].isin([0, 1])].copy()
        data["escalation_label"] = data["escalation_label"].astype(int)
        datasets[checkpoint] = data.set_index("conversation_id", drop=False)

    common_ids = (
        datasets[3].index.intersection(datasets[5].index)
    )
    if len(common_ids) < 25:
        raise ValueError(f"Too few shared conversations: {len(common_ids)}")

    results = []
    cv = StratifiedKFold(
        n_splits=5, shuffle=True, random_state=RANDOM_STATE
    )

    for checkpoint in CHECKPOINTS:
        data = datasets[checkpoint].loc[common_ids].copy()
        X = data["customer_text"]
        y = data["escalation_label"]

        if y.value_counts().min() < 5:
            raise ValueError("Each class needs at least 5 examples for 5-fold CV.")

        # Every prediction is generated by a model that did not train on
        # that conversation's fold.
        model = make_model()
        probabilities = cross_val_predict(
            model, X, y, cv=cv, method="predict_proba"
        )[:, 1]
        predictions = (probabilities >= 0.5).astype(int)

        metrics = {
            "checkpoint_messages": checkpoint,
            "conversations": len(data),
            "not_escalated": int((y == 0).sum()),
            "escalated": int((y == 1).sum()),
            "accuracy": accuracy_score(y, predictions),
            "precision": precision_score(y, predictions, zero_division=0),
            "recall": recall_score(y, predictions, zero_division=0),
            "f1": f1_score(y, predictions, zero_division=0),
            "roc_auc": roc_auc_score(y, probabilities),
            "pr_auc": average_precision_score(y, probabilities),
        }
        results.append(metrics)

        print(f"\n{'=' * 55}")
        print(f"TEXT MODEL — FIRST {checkpoint} MESSAGES")
        print(f"Conversations: {len(data)}")
        print("Label counts:", y.value_counts().sort_index().to_dict())
        for name in (
            "accuracy", "precision", "recall", "f1", "roc_auc", "pr_auc"
        ):
            print(f"{name.upper()}: {metrics[name]:.3f}")

        print("Confusion matrix [ [TN, FP], [FN, TP] ]:")
        print(confusion_matrix(y, predictions, labels=[0, 1]))
        print(classification_report(
            y, predictions,
            labels=[0, 1],
            target_names=["Not escalated", "Escalated"],
            zero_division=0,
        ))

        # Majority-class baseline for context.
        dummy = DummyClassifier(strategy="most_frequent")
        dummy_predictions = cross_val_predict(dummy, X.to_frame(), y, cv=cv)
        print(
            "Majority baseline accuracy:",
            f"{accuracy_score(y, dummy_predictions):.3f}",
        )

    report = pd.DataFrame(results)
    report_path = REPORT_DIR / "text_model_cross_validation.csv"
    report.to_csv(report_path, index=False)

    print("\nCHECKPOINT COMPARISON")
    print(report.to_string(index=False, float_format=lambda v: f"{v:.3f}"))
    print(f"\nSaved report: {report_path}")
    print(
        "\nNote: results are exploratory. The 107 conversations are a small, "
        "selectively annotated sample; labels describe eventual outcomes, "
        "and escalation onset time is unknown."
    )


if __name__ == "__main__":
    main()
